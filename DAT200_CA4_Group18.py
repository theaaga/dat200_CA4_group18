# Calculate the overall churn rate for reference in plots
overall = train_df["Churn"].mean()

# Define a function to plot churn rate by category
def churn_rate_plot(col, ax, title=None):
    """Bar plot of churn rate per category, with group sizes (n) under the labels."""
    # Compute churn rate and group sizes
    stats = train_df.groupby(col)["Churn"].agg(rate="mean", n="size").reset_index()
    # Create bar plot
    sns.barplot(data=stats, x=col, y="rate", ax=ax, color="steelblue")
    # Format the overall churn rate line and add it to the plot
    ax.axhline(overall, color="red", linestyle="--", linewidth=1,
               label=f"Overall ({overall:.1%})")
    # Add percentage labels on top of the bars
    ax.bar_label(ax.containers[0], labels=[f"{r:.1%}" for r in stats["rate"]], fontsize=9)
    # Set x-ticks and labels with group sizes
    ax.set_xticks(range(len(stats)))
    ax.set_xticklabels([f"{c}\n(n={n})" for c, n in zip(stats[col], stats["n"])])
    # Set title and labels, format y-axis as percentage
    ax.set_title(title or f"Churn rate by {col}")
    ax.set_xlabel("")
    ax.set_ylabel("Churn rate")
    ax.yaxis.set_major_formatter(plt.matplotlib.ticker.PercentFormatter(1.0))
    # Add legend 
    ax.legend()

