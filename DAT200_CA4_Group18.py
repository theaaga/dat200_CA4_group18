# ## Data cleaning

# As we saw, there were no missing, duplicate or impossible values in either the train set or test set. We will keep outliers since they are plausible values and can contribute meaningful information to the model. For example, we see in the plot for churn rates by CustomerServiceCall that the rate increases significantly for higher numbers of calls. 
# 
# For the cleaning we will do the following:
# - Change InternationalPlan and VoiceMailPlan to binary (yes=1, no=0)
# - AreaCode to string, so its treated as a category
# - Drop CustomerId from the features, but keep the testIDs for the Kaggle submission
# 
# We create a function, so it can easily be reused when training our models. 

# In[122]:


def clean(df):
    df = df.copy()

    # Convert InternationalPlan and VoiceMailPlan to binary
    for col in ["InternationalPlan", "VoiceMailPlan"]:
        df[col] = df[col].map({"yes": 1, "no": 0})

    # Convert AreaCode to string
    df["AreaCode"] = df["AreaCode"].astype(str)

    # Drop CustomerId, since it is an identifier and not a feature
    df = df.drop(columns=["CustomerId"], errors="ignore")

    # Double check that there are no missing values
    assert df.isnull().sum().sum() == 0

    return df



# ## Create Cross-Validation setup

# Use StratifiedKFold from Scikit-learn to create cross-validation setup to be used when training models. 
# 
# * 5 folds of 700 customers each. Since there are only about 490 churners, this is a good amount of folds to ensure there are enough churners in each validation fold
# * Shuffle the rows before splitting, so folds don't depend on the order of the file
# * use random_state=42, so the shuffle is reproducible and all group members get identical folds 
# * Stratified means that every fold keeps the same churn percentage as the full training set, 14.1%. 

# In[123]:


RANDOM_STATE = 42
SCORING = "f1_macro" # primary evaluation metric

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)


# ## Modelling

# We make two required pipelines: one with regularization (logistic regression) and one with a kernel and dimensionality reduction (PCA + SVM). We also try gradient boosting to see if we can get a better model. All models are tuned with GridSearchCV using the same `cv` and `SCORING` as defined above, so the comparison is fair.
# 
# The code for the modelling is generated with help from Claude: https://claude.ai/.

# ### Prepare data

# In[124]:


# Clean train and test with the function from the data cleaning
X = clean(train_df.drop(columns=["Churn"]))
y = train_df["Churn"]
X_test = clean(test_df)
test_ids = test_df["CustomerId"]  # keep for the Kaggle submission


# ### Feature engineering

# The Charge columns are just the Minutes multiplied by a fixed price (correlation 1.0), so they give no new information. Instead we make some new features:
# - Total minutes, total calls and total charge over the whole day, since customers with a high total bill may be more likely to leave
# - A flag for 4 or more customer service calls, since we saw that the churn rate increases a lot from 4 calls

# In[125]:


def add_features(df):
    df = df.copy()
    periods = ["Day", "Eve", "Night", "Intl"]

    # Totals over all periods
    df["TotalMinutes"] = df[[p + "Minutes" for p in periods]].sum(axis=1)
    df["TotalCalls"] = df[[p + "Calls" for p in periods]].sum(axis=1)
    df["TotalCharge"] = df[[p + "Charge" for p in periods]].sum(axis=1)

    # Flag for many customer service calls
    df["ManyServiceCalls"] = (df["CustomerServiceCalls"] >= 4).astype(int)

    # Drop the charge columns for each period
    df = df.drop(columns=[p + "Charge" for p in periods])
    return df

X = add_features(X)
X_test = add_features(X_test)
X.head()


# ### Preprocessing

# - State and AreaCode are categorical, so they are one-hot encoded
# - The numerical features are standardized, which is important for logistic regression and SVM
# 
# The preprocessing is put inside each pipeline, so it is only fitted on the training folds in the cross-validation (no data leakage).

# In[126]:


cat_cols = ["State", "AreaCode"]
num_cols = [col for col in X.columns if col not in cat_cols]

preprocessor = ColumnTransformer([
    ("cat", OneHotEncoder(handle_unknown="ignore", sparse_output=False), cat_cols),
    ("num", StandardScaler(), num_cols),
])


# ### Pipeline 1: Logistic regression (regularization)

# `C` is the inverse of the regularization strength (small C = strong regularization). `l1_ratio=0` gives L2 regularization and `l1_ratio=1` gives L1 regularization, which can set coefficients to zero. We use `class_weight="balanced"` because the classes are imbalanced.

# In[127]:


pipe_lr = Pipeline([
    ("preprocess", preprocessor),
    ("clf", LogisticRegression(solver="saga", class_weight="balanced", max_iter=5000))
])

param_grid_lr = {
    "clf__C": [0.001, 0.003, 0.01, 0.1, 1, 10],
    "clf__l1_ratio": [0, 1],  # 0 = L2, 1 = L1
}

grid_lr = GridSearchCV(pipe_lr, param_grid_lr, scoring=SCORING, cv=cv, n_jobs=-1)
grid_lr.fit(X, y)

print("Best score:", round(grid_lr.best_score_, 4))
print("Best params:", grid_lr.best_params_)


# The best logistic regression gets a macro F1 of 0.78. It uses strong L1 regularization (C=0.003), which sets many of the coefficients to zero. The score is quite low, which tells us that a linear model is not able to capture the relationship between the features and churn very well.

# ### Pipeline 2: PCA + SVM (kernel and dimensionality reduction)

# After one-hot encoding there are about 70 features, most of them from State. PCA reduces the number of features, and the SVM with RBF kernel can find a non-linear decision boundary. We tune the number of PCA components together with `C` and `gamma`.

# In[128]:


pipe_svm = Pipeline([
    ("preprocess", preprocessor),
    ("pca", PCA(random_state=RANDOM_STATE)),
    ("clf", SVC(kernel="rbf"))
])

param_grid_svm = {
    "pca__n_components": [10, 20, 40],
    "clf__C": [1, 10, 100],
    "clf__gamma": ["scale", 0.01, 0.03],
    "clf__class_weight": [None, "balanced"],
}

grid_svm = GridSearchCV(pipe_svm, param_grid_svm, scoring=SCORING, cv=cv, n_jobs=-1)
grid_svm.fit(X, y)

print("Best score:", round(grid_svm.best_score_, 4))
print("Best params:", grid_svm.best_params_)


# PCA + SVM gets a macro F1 of 0.87, which is a lot better than logistic regression. The best model uses 20 PCA components. Since the SVM with RBF kernel can make a non-linear decision boundary, this confirms that the relationship is non-linear.

# ### Pipeline 3: Gradient boosting (better model)

# Since the relationship between the features and churn seems to be non-linear, we also try a tree-based model. Gradient boosting builds many small decision trees, where each new tree corrects the errors of the previous ones.

# In[129]:


pipe_gb = Pipeline([
    ("preprocess", preprocessor),
    ("clf", HistGradientBoostingClassifier(random_state=RANDOM_STATE))
])

param_grid_gb = {
    "clf__learning_rate": [0.05, 0.1],
    "clf__max_iter": [200, 400],
    "clf__min_samples_leaf": [20, 50],
    "clf__class_weight": [None, "balanced"],
}

grid_gb = GridSearchCV(pipe_gb, param_grid_gb, scoring=SCORING, cv=cv, n_jobs=-1)
grid_gb.fit(X, y)

print("Best score:", round(grid_gb.best_score_, 4))
print("Best params:", grid_gb.best_params_)


# ### Comparing

# In[130]:


results = pd.DataFrame({
    "Model": ["Logistic regression", "PCA + SVM", "Gradient boosting"],
    "Best CV macro F1": [grid_lr.best_score_, grid_svm.best_score_, grid_gb.best_score_]
})
results = results.sort_values("Best CV macro F1", ascending=False)
results


# Gradient boosting is clearly the best model with a macro F1 of 0.95, and is chosen as our final model. Both required pipelines perform worse, but PCA + SVM is better than logistic regression.

# ### Final evaluation

# To evaluate the best model we use `cross_val_predict`, so each customer is predicted by a model that has not seen that customer during training.

# In[131]:


best_model = grid_gb.best_estimator_

# Predictions from cross-validation
y_pred = cross_val_predict(best_model, X, y, cv=cv)

print(classification_report(y, y_pred, target_names=["Stays (0)", "Leaves (1)"]))
ConfusionMatrixDisplay.from_predictions(y, y_pred, display_labels=["Stays", "Leaves"], cmap="Blues")
